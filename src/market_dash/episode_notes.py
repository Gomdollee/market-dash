def news_search_url(query: str, start: str, end: str) -> str | None:
    """그 기간 한국어 뉴스 검색 링크. 2005년 이전은 검색 결과가 거의 없어 생략."""
    if start < "2005-01-01":
        return None
    from urllib.parse import quote

    return f"https://news.google.com/search?q={quote(f'{query} after:{start} before:{end}')}&hl=ko&gl=KR&ceid=KR:ko"
